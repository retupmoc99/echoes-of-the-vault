/**
 * Art pipeline: art-raw/  →  public/assets/  (+ src/data/assets.generated.ts)
 *
 *   art-raw/cards/shatter-lens.png      → public/assets/cards/shatter-lens.webp
 *   art-raw/enemies/Hollow Sentinel.png → public/assets/enemies/hollow-sentinel.webp
 *
 * - File names become content IDs (lowercased; spaces/underscores → hyphens).
 * - Each folder has a spec: size, fit, transparency, quality, file-size budget.
 * - Over budget? Quality steps down until it fits (or warns).
 * - Finally, every .webp in public/assets is listed in assets.generated.ts,
 *   which is how the game knows which art exists.
 *
 * Usage:  npm run art
 * See ART_GUIDE.md for the specs and prompts.
 */
import sharp from 'sharp';
import { mkdir, readdir, stat, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import path from 'node:path';

const RAW = 'art-raw';
const OUT = 'public/assets';
const MANIFEST = 'src/data/assets.generated.ts';
const INPUT_EXT = new Set(['.png', '.jpg', '.jpeg', '.webp', '.tif', '.tiff']);

/** Keep in sync with the table in ART_GUIDE.md. */
const SPECS = {
  cards: { width: 512, height: 384, fit: 'cover', alpha: false, quality: 78, budgetKB: 40 },
  enemies: { width: 768, height: 768, fit: 'contain', alpha: true, quality: 80, budgetKB: 90 },
  relics: { width: 256, height: 256, fit: 'contain', alpha: true, quality: 82, budgetKB: 25 },
  backgrounds: { width: 1080, height: 1920, fit: 'cover', alpha: false, quality: 68, budgetKB: 250 },
  ui: { width: 192, height: 192, fit: 'contain', alpha: true, quality: 85, budgetKB: 15 },
};

const toId = (file) =>
  path
    .parse(file)
    .name.trim()
    .toLowerCase()
    .replace(/[\s_]+/g, '-')
    .replace(/[^a-z0-9-]/g, '');

async function convert(folder, file, spec) {
  const src = path.join(RAW, folder, file);
  const id = toId(file);
  const dest = path.join(OUT, folder, `${id}.webp`);
  const meta = await sharp(src).metadata();
  const notes = [];

  if (spec.alpha && !meta.hasAlpha) notes.push('no transparency: remove the background first (see ART_GUIDE.md)');
  const ratio = (meta.width ?? 1) / (meta.height ?? 1);
  const want = spec.width / spec.height;
  if (Math.abs(ratio - want) / want > 0.15) notes.push(`aspect ${ratio.toFixed(2)} differs from ${want.toFixed(2)}: it will be ${spec.fit === 'cover' ? 'cropped' : 'padded'}`);

  let quality = spec.quality;
  let buffer;
  for (;;) {
    buffer = await sharp(src)
      .resize(spec.width, spec.height, {
        fit: spec.fit,
        background: { r: 0, g: 0, b: 0, alpha: 0 },
        withoutEnlargement: false,
      })
      .webp({ quality, alphaQuality: 90, effort: 6, smartSubsample: true })
      .toBuffer();
    if (buffer.length <= spec.budgetKB * 1024 || quality <= 50) break;
    quality -= 6;
  }

  await writeFile(dest, buffer);
  const kb = (buffer.length / 1024).toFixed(1);
  if (buffer.length > spec.budgetKB * 1024) notes.push(`${kb} KB is over the ${spec.budgetKB} KB budget even at quality 50`);
  const flag = notes.length ? '  ⚠ ' + notes.join('; ') : '';
  console.log(`  ${folder}/${id}.webp  ${kb} KB  (q${quality})${flag}`);
}

async function listWebp() {
  const keys = [];
  for (const folder of Object.keys(SPECS)) {
    const dir = path.join(OUT, folder);
    if (!existsSync(dir)) continue;
    for (const f of await readdir(dir)) if (f.endsWith('.webp')) keys.push(`${folder}/${f.slice(0, -5)}`);
  }
  return keys.sort();
}

let converted = 0;
for (const [folder, spec] of Object.entries(SPECS)) {
  await mkdir(path.join(OUT, folder), { recursive: true });
  const dir = path.join(RAW, folder);
  if (!existsSync(dir)) continue;
  const files = (await readdir(dir)).filter((f) => INPUT_EXT.has(path.extname(f).toLowerCase()));
  if (files.length) console.log(`${folder}/ (${spec.width}×${spec.height}, budget ${spec.budgetKB} KB)`);
  for (const f of files) {
    if (!(await stat(path.join(dir, f))).isFile()) continue;
    await convert(folder, f, spec);
    converted++;
  }
}

const keys = await listWebp();
const body = `// Generated by \`npm run art\`. Do not edit by hand.
// Lists the optimized images in public/assets/, as "folder/content-id".
export const AVAILABLE_ART: readonly string[] = ${keys.length ? `[\n${keys.map((k) => `  '${k}',`).join('\n')}\n]` : '[]'};
`;
await writeFile(MANIFEST, body);

let totalKB = 0;
for (const k of keys) totalKB += (await stat(path.join(OUT, `${k}.webp`))).size / 1024;
console.log(`\nConverted ${converted} file(s). ${keys.length} image(s) available, ${(totalKB / 1024).toFixed(2)} MB total.`);
console.log(`Updated ${MANIFEST}. Restart \`npm run dev\` if it is running.`);
